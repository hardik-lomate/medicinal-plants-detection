def build_image_type_manifest():
    """Each image's label is simply 'leaf' or 'whole_plant'."""
    print('\n--- Building image_type manifest ---')

    rows = []
    for dataset_type, ds_path in [('leaf', cfg.LEAF_DATASET_DIR), ('whole_plant', cfg.PLANT_DATASET_DIR)]:
        ds_path = Path(ds_path)
        class_folders = sorted([d for d in ds_path.iterdir() if d.is_dir()])
        for cls_dir in class_folders:
            files = find_image_files(cls_dir)
            for f in files:
                if is_valid_image(f):
                    rows.append({
                        'filepath': str(f),
                        'class_name': dataset_type,
                        'normalized_class': dataset_type,
                        'dataset_type': 'image_type',
                        'split': None,  # assigned below
                    })

    random.seed(cfg.SEED)
    random.shuffle(rows)
    n = len(rows)
    n_train = int(n * cfg.TRAIN_RATIO)
    n_val = int(n * cfg.VAL_RATIO)

    for i, row in enumerate(rows):
        if i < n_train:
            row['split'] = 'train'
        elif i < n_train + n_val:
            row['split'] = 'val'
        else:
            row['split'] = 'test'

    with open(cfg.IMAGE_TYPE_MANIFEST_CSV, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['filepath', 'class_name', 'normalized_class', 'dataset_type', 'split'])
        writer.writeheader()
        writer.writerows(rows)

    leaf_count = sum(1 for r in rows if r['class_name'] == 'leaf')
    plant_count = sum(1 for r in rows if r['class_name'] == 'whole_plant')
    print(f'  Leaf images    : {leaf_count}')
    print(f'  Plant images   : {plant_count}')
    print(f'  Total          : {len(rows)}')
    print(f'  Output         : {cfg.IMAGE_TYPE_MANIFEST_CSV}')

    return {'total': len(rows), 'leaf': leaf_count, 'plant': plant_count}


