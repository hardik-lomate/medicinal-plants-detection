def compute_md5(filepath, chunk=65536):
    h = hashlib.md5()
    try:
        with open(filepath, 'rb') as f:
            while True:
                buf = f.read(chunk)
                if not buf:
                    break
                h.update(buf)
        return h.hexdigest()
    except Exception:
        return None


def find_image_files(folder):
    folder = Path(folder)
    found = []
    for root, dirs, files in os.walk(folder):
        for fname in files:
            if Path(fname).suffix.lower() in cfg.IMAGE_EXTENSIONS:
                found.append(Path(root) / fname)
    return found


def is_valid_image(filepath):
    if not PIL_OK:
        return True  # assume valid if PIL not available
    try:
        with Image.open(filepath) as img:
            img.verify()
        return True
    except Exception:
        return False


def split_files(files, train_r, val_r, test_r, seed):
    """Stratified random split by hash to prevent near-duplicate leakage."""
    random.seed(seed)
    # Remove exact hash duplicates
    seen = {}
    unique = []
    for f in files:
        md5 = compute_md5(f)
        if md5 is None:
            continue
        if md5 not in seen:
            seen[md5] = f
            unique.append(f)

    random.shuffle(unique)
    n = len(unique)
    n_train = int(n * train_r)
    n_val = int(n * val_r)
    train = unique[:n_train]
    val = unique[n_train:n_train + n_val]
    test = unique[n_train + n_val:]
    return train, val, test


# ---------------------------------------------------------------------------
# Load class normalization mappings
# ---------------------------------------------------------------------------

def load_normalization():
    """Load the leaf and plant class mappings generated by normalize_classes.py."""
    leaf_map = {}   # raw_folder_name -> normalized_name
    plant_map = {}

    if cfg.LEAF_CLASSES_JSON.exists():
        with open(cfg.LEAF_CLASSES_JSON, encoding='utf-8') as f:
            data = json.load(f)
        for entry in data.get('class_details', []):
            leaf_map[entry['raw_folder_name']] = entry['normalized_name']
    else:
        print(f'[WARNING] {cfg.LEAF_CLASSES_JSON} not found. Run normalize_classes.py first.')

    if cfg.PLANT_CLASSES_JSON.exists():
        with open(cfg.PLANT_CLASSES_JSON, encoding='utf-8') as f:
            data = json.load(f)
        for entry in data.get('class_details', []):
            plant_map[entry['raw_folder_name']] = entry['normalized_name']
    else:
        print(f'[WARNING] {cfg.PLANT_CLASSES_JSON} not found. Run normalize_classes.py first.')

    return leaf_map, plant_map


