# Build manifest for one dataset
# ---------------------------------------------------------------------------

def build_manifest(ds_path, dataset_type, norm_map, manifest_path):
    ds_path = Path(ds_path)
    print(f'\n--- Building {dataset_type} manifest ---')
    print(f'    Source: {ds_path}')
    print(f'    Output: {manifest_path}')

    rows = []
    class_stats = {}
    excluded_classes = []

    class_folders = sorted([d for d in ds_path.iterdir() if d.is_dir()])

    for cls_dir in class_folders:
        raw_name = cls_dir.name
        norm_name = norm_map.get(raw_name, raw_name)

        files = find_image_files(cls_dir)

        # Filter corrupted images
        valid_files = []
        for f in files:
            if is_valid_image(f):
                valid_files.append(f)

        n = len(valid_files)

        if n < cfg.MIN_IMAGES_PER_CLASS:
            print(f'  [SKIP] {raw_name} ({norm_name}): only {n} valid images < {cfg.MIN_IMAGES_PER_CLASS} minimum')
            excluded_classes.append({'folder': raw_name, 'normalized': norm_name, 'count': n, 'reason': 'insufficient_data'})
            continue

        train_files, val_files, test_files = split_files(
            valid_files, cfg.TRAIN_RATIO, cfg.VAL_RATIO, cfg.TEST_RATIO, cfg.SEED
        )

        for split_name, split_files_list in [('train', train_files), ('val', val_files), ('test', test_files)]:
            for fpath in split_files_list:
                rows.append({
                    'filepath': str(fpath),
                    'class_name': raw_name,
                    'normalized_class': norm_name,
                    'dataset_type': dataset_type,
                    'split': split_name,
                })

        class_stats[raw_name] = {
            'normalized': norm_name,
            'total': n,
            'train': len(train_files),
            'val': len(val_files),
            'test': len(test_files),
        }
        print(f'  [OK]   {raw_name:<35} ({norm_name:<30}) -> train={len(train_files)}, val={len(val_files)}, test={len(test_files)}')

    # Write CSV
    manifest_path = Path(manifest_path)
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    with open(manifest_path, 'w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=['filepath', 'class_name', 'normalized_class', 'dataset_type', 'split'])
        writer.writeheader()
        writer.writerows(rows)

    train_total = sum(1 for r in rows if r['split'] == 'train')
    val_total = sum(1 for r in rows if r['split'] == 'val')
    test_total = sum(1 for r in rows if r['split'] == 'test')

    print(f'\n  Classes included : {len(class_stats)}')
    print(f'  Classes excluded : {len(excluded_classes)} (insufficient data)')
    print(f'  Train            : {train_total}')
    print(f'  Val              : {val_total}')
    print(f'  Test             : {test_total}')
    print(f'  Total rows       : {len(rows)}')

    return {
        'manifest_path': str(manifest_path),
        'dataset_type': dataset_type,
        'num_included_classes': len(class_stats),
        'num_excluded_classes': len(excluded_classes),
        'excluded_classes': excluded_classes,
        'class_stats': class_stats,
        'train_total': train_total,
        'val_total': val_total,
        'test_total': test_total,
    }


